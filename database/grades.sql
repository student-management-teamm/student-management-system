-- Component scores of each student in each course (0-10, NULL = not graded yet)
CREATE TABLE IF NOT EXISTS `grades` (
  `GradeID` int NOT NULL AUTO_INCREMENT,
  `StudentID` int NOT NULL,
  `SubjectID` int NOT NULL,
  `AttendanceScore` decimal(4,2) DEFAULT NULL,
  `MidtermScore` decimal(4,2) DEFAULT NULL,
  `FinalScore` decimal(4,2) DEFAULT NULL,
  PRIMARY KEY (`GradeID`),
  UNIQUE KEY `UQ_Grades_Student_Subject` (`StudentID`, `SubjectID`),
  KEY `FK_Grades_Subjects` (`SubjectID`),
  CONSTRAINT `FK_Grades_Students` FOREIGN KEY (`StudentID`) REFERENCES `students` (`StudentID`),
  CONSTRAINT `FK_Grades_Subjects` FOREIGN KEY (`SubjectID`) REFERENCES `subjects` (`SubjectID`),
  CONSTRAINT `CK_Grades_Attendance` CHECK (`AttendanceScore` BETWEEN 0 AND 10),
  CONSTRAINT `CK_Grades_Midterm` CHECK (`MidtermScore` BETWEEN 0 AND 10),
  CONSTRAINT `CK_Grades_Final` CHECK (`FinalScore` BETWEEN 0 AND 10)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

